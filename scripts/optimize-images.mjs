import sharp from 'sharp';
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';

// Originals are preserved. Responsive derivatives are build artifacts in dist/,
// while this small, deterministic metadata module is shared by React and SSR.
sharp.concurrency(2);
const sourceDir = 'public/images';
const outputDir = 'public/images/optimized';
await mkdir(outputDir, { recursive: true });
await mkdir('src/generated', { recursive: true });
const files = [];
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name === 'optimized') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(full);
    else if (/\.(jpe?g|png|webp)$/i.test(entry.name)) files.push(full);
  }
}
await walk(sourceDir);
files.sort();
const metadata = {};
let count = 0;
for (let start = 0; start < files.length; start += 4) {
  await Promise.all(files.slice(start, start + 4).map(async (file) => {
    const source = sharp(file);
    const { width, height } = await source.metadata();
    if (!width || !height) throw new Error(`Missing image dimensions: ${file}`);
    const relative = path.relative(sourceDir, file).split(path.sep).join('/');
    const stem = relative.replace(/\.[^.]+$/, '');
    const widths = [...new Set([480, 800, 1200, width].filter((w) => w <= width))].sort((a, b) => a - b);
    metadata[`/images/${relative}`] = { width, height, widths };
    await Promise.all(widths.flatMap((w) => ['avif', 'webp'].map(async (format) => {
      const target = path.join(outputDir, `${stem}-${w}.${format}`);
      await mkdir(path.dirname(target), { recursive: true });
      const sourceStat = await stat(file);
      try { if ((await stat(target)).mtimeMs >= sourceStat.mtimeMs) { count++; return; } } catch { /* first build */ }
      const image = sharp(file).rotate().resize({ width: w, withoutEnlargement: true });
      if (format === 'avif') await image.avif({ quality: 52, effort: 3 }).toFile(target);
      else await image.webp({ quality: 78, effort: 4 }).toFile(target);
      count++;
    })));
  }));
}
const ordered = Object.fromEntries(Object.keys(metadata).sort().map((key) => [key, metadata[key]]));
await writeFile('src/generated/images.ts', `// Generated by scripts/optimize-images.mjs; do not edit by hand.\nexport const IMAGE_META = ${JSON.stringify(ordered, null, 2)} as const;\nexport type ImagePath = keyof typeof IMAGE_META;\nexport const optimizedSrc = (src: string, width: number, format: 'avif' | 'webp') => \`/images/optimized/\${src.replace(/^\\/images\\//, '').replace(/\\.[^.]+$/, '')}-\${width}.\${format}\`;\n`);
console.log(`Optimized ${files.length} source images into ${count} AVIF/WebP derivatives.`);
