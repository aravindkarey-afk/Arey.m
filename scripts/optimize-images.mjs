/**
 * Optimizes the site's photos in `public/images/reference/`.
 *
 * For every committed `*.webp` photo this script:
 *   1. Writes an AVIF sibling (`*.avif`) quality 45 — AVIF is served to browsers
 *      that support it via <picture>, WebP stays as the universal fallback.
 *   2. For photos wider than 640px, writes a 480w variant (`*-480.webp` / `*-480.avif`)
 *      for small screens.
 *   3. For photos wider than 800px, writes an 800w variant (`*-800.webp` / `*-800.avif`).
 *   4. Regenerates `src/lib/imageManifest.ts` with intrinsic dimensions and the
 *      available variant widths so <Picture> can build correct srcSets and
 *      width/height (no broken images, no layout shift).
 *
 * Run with: npm run optimize:images
 * The generated files are committed to the repo, so this only needs to run
 * when the underlying photos change.
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = path.join(root, "public", "images", "reference");
const manifestPath = path.join(root, "src", "lib", "imageManifest.ts");

const files = (await readdir(imagesDir)).filter((file) => file.endsWith(".webp") && !/-\d+\.webp$/.test(file));

if (files.length === 0) {
  console.error("No source .webp images found in", imagesDir);
  process.exit(1);
}

const manifest = {};

for (const file of files.sort()) {
  const base = file.replace(/\.webp$/, "");
  const source = path.join(imagesDir, file);
  const image = sharp(source);
  const { width, height } = await image.metadata();
  if (!width || !height) {
    console.error("Could not read dimensions of", file);
    process.exit(1);
  }

  // The committed source .webp is already well compressed — do not re-encode it.
  // We only emit AVIF for the full-size image and downscaled variants + their AVIFs.
  const variants = [{ width, suffix: "" }];
  if (width > 640) variants.push({ width: 480, suffix: "-480" });
  if (width > 800) variants.push({ width: 800, suffix: "-800" });

  const widths = new Set([width]);
  for (const variant of variants) {
    const pipeline = variant.suffix
      ? image.clone().resize({ width: variant.width, withoutEnlargement: true })
      : image.clone();
    const avifName = `${base}${variant.suffix}.avif`;
    await pipeline.avif({ quality: 45, effort: 6 }).toFile(path.join(imagesDir, avifName));
    if (variant.suffix) {
      const webpName = `${base}${variant.suffix}.webp`;
      await image.clone().resize({ width: variant.width, withoutEnlargement: true }).webp({ quality: 80, effort: 6 }).toFile(path.join(imagesDir, webpName));
      widths.add(variant.width);
    }
  }

  manifest[base] = { width, height, widths: [...widths].sort((a, b) => a - b) };
  console.log(`optimized ${file} (${width}x${height})`);
}

const header = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
// Intrinsic dimensions and available responsive variant widths for the
// photos in public/images/reference/. Used by <Picture>.
export type ImageMeta = { width: number; height: number; widths: number[] };
export const IMAGE_META: Record<string, ImageMeta> = `;
const body = JSON.stringify(manifest, null, 2).replace(/"([^"]+)":/g, "$1:");
await writeFile(manifestPath, `${header}${body};\n`);
console.log(`\nWrote ${manifestPath} with ${Object.keys(manifest).length} entries.`);
